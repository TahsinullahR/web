async def _tool_project_write_file(args: dict) -> dict:
    from .. import repo
    from ..sandbox import write_file, valid_project_id
    conn = _require_conn()
    pid = valid_project_id(str(args.get("project_id", "")))
    path = str(args.get("path", ""))[:256]
    content = str(args.get("content", ""))
    if not await repo.get_project(conn, pid):
        return {"ok": False, "error": f"Project {pid} not found"}
    write_file(pid, path, content)
    await repo.save_project_file(conn, pid, path, content)
    return {"ok": True, "summary": f"Wrote {path} ({len(content)} chars) to project {pid}"}


async def _tool_project_validate(args: dict) -> dict:
    """Verify generated HTML actually parses & referenced local files exist."""
    from .. import sandbox
    from ..sandbox import valid_project_id
    import re as _re
    pid = valid_project_id(str(args.get("project_id", "")))
    base = sandbox.project_dir(pid)
    idx = base / "index.html"
    if not idx.is_file():
        return {"ok": False, "error": "index.html missing"}
    html = idx.read_text(encoding="utf-8", errors="replace")
    problems = []
    if "<html" not in html.lower():
        problems.append("no <html> tag")
    for m in _re.findall(r'(?:src|href)="([^"]+)"', html):
        if m.startswith(("http", "#", "mailto:")):
            continue
        if not (base / m).is_file():
            problems.append(f"referenced file missing: {m}")
    if problems:
        return {"ok": False, "error": "; ".join(problems)}
    return {"ok": True, "summary": f"Verified index.html: structure OK, all {len(_re.findall(chr(34)+'?[^\"<>]*\\.(?:css|js)', html)) or 0}+ local asset references exist"}


async def _tool_delete_project(args: dict) -> dict:
    from .. import repo
    from ..sandbox import delete_project_dir, valid_project_id
    conn = _require_conn()
    pid = valid_project_id(str(args.get("project_id", "")))
    ok = await repo.delete_project(conn, pid)
    if not ok:
        return {"ok": False, "error": "Project not found"}
    delete_project_dir(pid)
    return {"ok": True, "summary": f"Deleted project {pid}"}


def bootstrap_tools() -> ToolRegistry:
    if "project_create" in registry.names():
        return registry
    registry.register(Tool(
        name="project_create",
        description="Create a static website project with starter HTML/CSS/JS files.",
        fn=_tool_project_create,
    ))
    registry.register(Tool(
        name="project_write_file",
        description="Write/overwrite one file inside a project workspace (safe paths only).",
        fn=_tool_project_write_file,
    ))
    registry.register(Tool(
        name="project_validate",
        description="Validate a project's index.html structure and local asset references.",
        fn=_tool_project_validate,
    ))
    registry.register(Tool(
        name="project_delete",
        description="Delete a project and its files. Destructive.",
        fn=_tool_delete_project,
        needs_approval=True,
    ))
    return registry
