"""Tool registry for the agent engine.

Every tool is an explicit, validated backend function — the model NEVER emits
shell commands that get executed directly. Tools receive parsed JSON args,
run under timeouts, and return structured results. Destructive/consequential
tools are flagged needs_approval=True and require a human approval step.
"""
from __future__ import annotations

import asyncio
import json
from dataclasses import dataclass, field
from typing import Any, Awaitable, Callable

ToolFn = Callable[[dict], Awaitable[dict]]


@dataclass
class Tool:
    name: str
    description: str
    fn: ToolFn
    needs_approval: bool = False
    timeout_seconds: float = 60.0
    args_schema: dict = field(default_factory=dict)


class ToolRegistry:
    def __init__(self) -> None:
        self._tools: dict[str, Tool] = {}

    def register(self, tool: Tool) -> None:
        if tool.name in self._tools:
            raise ValueError(f"Duplicate tool: {tool.name}")
        self._tools[tool.name] = tool

    def get(self, name: str) -> Tool | None:
        return self._tools.get(name)

    def names(self) -> list[str]:
        return sorted(self._tools)

    def describe_for_prompt(self) -> str:
        return "\n".join(
            f"- {t.name}: {t.description} (approval required: {t.needs_approval})"
            for t in self._tools.values()
        )

    async def run(self, name: str, args: dict) -> dict:
        tool = self._tools.get(name)
        if not tool:
            return {"ok": False, "error": f"Unknown tool '{name}'. Available: {self.names()}"}
        try:
            return await asyncio.wait_for(tool.fn(args), timeout=tool.timeout_seconds)
        except asyncio.TimeoutError:
            return {"ok": False, "error": f"Tool '{name}' timed out after {tool.timeout_seconds}s"}
        except Exception as e:  # never leak stack traces; record safe summary
            return {"ok": False, "error": f"Tool '{name}' failed: {type(e).__name__}: {str(e)[:200]}"}


registry = ToolRegistry()

# Set by the FastAPI lifespan so tools can reach the shared DB connection.
_ctx: dict = {}


def set_app_context(conn) -> None:
    _ctx["conn"] = conn


def _require_conn():
    conn = _ctx.get("conn")
    if conn is None:
        raise RuntimeError("App DB context not initialized")
    return conn


def _json_arg(args: dict, key: str, default: Any = None) -> Any:
    v = args.get(key, default)
    if isinstance(v, str):
        try:
            return json.loads(v)
        except json.JSONDecodeError:
            return v
    return v


async def _tool_project_create(args: dict) -> dict:
    """Create a website project with starter files (used by the builder)."""
    from ..routers.projects import create_project_record
    conn = _require_conn()
    name = str(args.get("name", ""))[:64] or "generated-site"
    prompt = str(args.get("prompt", ""))[:4000]
    pid = await create_project_record(conn, name=name, kind="static", prompt=prompt,
                                      files=_starter_files(name))
    return {"ok": True, "project_id": pid,
            "summary": f"Created project '{name}' ({pid}) with index.html, style.css, script.js"}


